/**
 * The pre-1950 catalogue (SPEC2 M23, E-15) - sixty generations of rail, road
 * and water between 1850 and 1949, and NOTHING else.
 *
 * SPEC2 asks for these as "reine Katalogdaten", and the word is exact: this
 * file adds no mechanism at all. Era gating already existed and was already
 * data-driven - `commands/build.ts`, `vehicles/consist.ts` and
 * `vehicles/renewal.ts` have compared `world.date.year` against a spec's
 * `introYear`/`retireYear` since M3 - so a start year of 1850 and a table that
 * begins in 1850 are between them the whole of "a steam game". What M23
 * bundle 1 added beside this table is the start year itself (D-245).
 *
 * **Every entry retires in 1949 at the latest, and that is load-bearing.**
 * The alternative - an 1946 lorry still on sale in 1952 - would put new
 * candidates in front of `renewal.ts`'s total order and the AI's own ranking
 * in every 1950 world in the game, which would re-band every scenario of
 * section 19.4 inside the milestone that introduced the table (SPEC2
 * Fehlerkatalog 34). Closing the era block instead makes the claim provable
 * rather than hopeful: `tests/unit/eraCatalog.spec.ts` asserts that the set of
 * specs purchasable in any year from 1950 on is EXACTLY the pre-M23 set, id
 * for id. A vehicle BOUGHT in 1948 of course keeps running into the 1970s -
 * what closes is the shop, not the fleet.
 *
 * **No baked art, on purpose and within the ledger.** E-14 names "frühe Ären
 * 1850-1920" as procedural territory, and sixty models at eight facings would
 * be 480 atlas cells against the ~150 SPEC2's 6.1 books for the whole of M23 -
 * an unbooked overflow is Fehlerkatalog 40. So these sixty draw through
 * `shapes.ts`, the D-170 fallback floor that every catalogue entry has always
 * had, and this bundle books ZERO atlas cells. The coupling test of D-169 was
 * widened by exactly one named rule (`introYear < START_YEAR`) and still holds
 * both directions for everything else.
 *
 * All names are invented type designations, exactly as in the other three
 * catalogues. No real manufacturer, series, shipyard or railway appears
 * anywhere; that is a legal requirement, not a stylistic one.
 *
 * The numbers are a LADDER rather than a history: each generation is dearer,
 * heavier, stronger and faster than the one it replaces, and every decade from
 * the 1850s to the 1940s introduces at least one entry in each of the four
 * groups below (SPEC.md 11.5's "pro Jahrzehnt", carried back a century).
 * `tests/unit/eraCatalog.spec.ts` holds both properties.
 */

